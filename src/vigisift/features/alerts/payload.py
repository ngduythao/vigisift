"""Frigate's review payload (MQTT `<prefix>/reviews` and `GET /api/review`).

Data from another system, partly generated by a VLM: validate before use. Unknown
fields are ignored (a new Frigate field must not break us), but a field we use
with the wrong type or over its limit rejects the whole message.
"""

from datetime import UTC, datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, ValidationError

from vigisift.domain.alert import AlertSummary, AlertUpdate, Severity, ThreatLevel

# Frigate allows only letters, digits, `_` and `-` in camera and zone names. Review ids
# look like "1718987129.308396-fqk5ka".
_Name = Annotated[str, StringConstraints(pattern=r"^[A-Za-z0-9_-]{1,64}$")]
_ReviewId = Annotated[str, StringConstraints(pattern=r"^[A-Za-z0-9._-]{1,100}$")]
# Length limits so a model's rambling answer can't bloat the DB.
_Text = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=2000)]
_Short = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=300)]
_Timestamp = Annotated[float, Field(gt=0, allow_inf_nan=False)]


class _Model(BaseModel):
    model_config = ConfigDict(extra="ignore", frozen=True)


class _Metadata(_Model):
    title: _Short
    short_summary: _Text = Field(alias="shortSummary")
    scene: _Text
    confidence: float = Field(ge=0, le=1, allow_inf_nan=False)
    potential_threat_level: int = Field(ge=0, le=2)
    other_concerns: list[_Short] | None = Field(default=None, max_length=20)
    observations: list[_Short] | None = Field(default=None, max_length=20)


class _Data(_Model):
    objects: list[_Name] = Field(default_factory=list, max_length=50)
    zones: list[_Name] = Field(default_factory=list, max_length=50)
    metadata: _Metadata | None = None


class ReviewSegment(_Model):
    id: _ReviewId
    camera: _Name
    start_time: _Timestamp
    end_time: _Timestamp | None = None
    severity: Severity
    data: _Data = Field(default_factory=_Data)


class _ReviewMessage(_Model):
    type: Literal["new", "update", "end", "genai"]
    after: ReviewSegment


class InvalidReviewError(Exception):
    pass


def _time(seconds: float) -> datetime:
    return datetime.fromtimestamp(seconds, UTC)


def to_update(site_id: str, segment: ReviewSegment) -> AlertUpdate:
    """A review (from MQTT or the API) as one alert update.

    A summarised review has only approximate times: before sending the summary,
    Frigate widens `start_time`/`end_time` by up to 5 seconds at each end, and also
    saves the widened values in its DB.
    """
    metadata = segment.data.metadata
    if segment.end_time is not None and segment.end_time < segment.start_time:
        raise InvalidReviewError(f"{segment.id}: end_time before start_time")
    return AlertUpdate(
        site_id=site_id,
        review_id=segment.id,
        camera=segment.camera,
        severity=segment.severity,
        objects=tuple(sorted(set(segment.data.objects))),
        zones=tuple(sorted(set(segment.data.zones))),
        started_at=_time(segment.start_time),
        ended_at=_time(segment.end_time) if segment.end_time is not None else None,
        times_approximate=metadata is not None,
        summary=(
            AlertSummary(
                title=metadata.title,
                summary=metadata.short_summary,
                scene=metadata.scene,
                confidence=metadata.confidence,
                threat_level=ThreatLevel(metadata.potential_threat_level),
                other_concerns=tuple(metadata.other_concerns or ()),
                observations=tuple(metadata.observations or ()),
            )
            if metadata is not None
            else None
        ),
    )


def parse_review_message(site_id: str, raw: str | bytes) -> AlertUpdate:
    try:
        message = _ReviewMessage.model_validate_json(raw)
    except ValidationError as error:
        # Keep input out of logs: the payload can be long, and has model-generated text.
        fields = sorted({".".join(map(str, e["loc"])) for e in error.errors()})
        raise InvalidReviewError(f"bad payload at {', '.join(fields)}") from error
    return to_update(site_id, message.after)


def parse_review_segment(site_id: str, raw: Any) -> AlertUpdate:
    """One item of `GET /api/review`, the same shape as `after` on MQTT."""
    try:
        segment = ReviewSegment.model_validate(raw)
    except ValidationError as error:
        fields = sorted({".".join(map(str, e["loc"])) for e in error.errors()})
        raise InvalidReviewError(f"bad review at {', '.join(fields)}") from error
    return to_update(site_id, segment)
